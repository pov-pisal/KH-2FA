function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Detect brand details and return SVG logo markup for an account.
 * @param {string} issuer - Account issuer (e.g., "Facebook", "Google")
 * @param {string} label - Account label (e.g., "user@gmail.com")
 * @returns {object} { id, name, color, bgColor, borderColor, svg, isFallback }
 */
export function getBrandInfo(issuer = "", label = "") {
  const cleanIssuer = (issuer || "").trim();
  const cleanLabel = (label || "").trim();
  const searchTarget = `${cleanIssuer} ${cleanLabel}`.trim();

  // Try matching against catalogued brands
  for (const brand of BRAND_DEFINITIONS) {
    if (brand.regex.test(searchTarget)) {
      return {
        id: brand.id,
        name: brand.name,
        color: brand.color,
        bgColor: brand.bgColor,
        borderColor: brand.borderColor,
        svg: brand.svg,
        isFallback: false,
      };
    }
  }

  // Fallback: Generate a crisp initial letter avatar with a stylized security shield
  const displayName = cleanIssuer || cleanLabel || "TOTP";
  const firstLetter = displayName.charAt(0).toUpperCase() || "🔐";
  const palette = FALLBACK_PALETTES[hashString(displayName) % FALLBACK_PALETTES.length];

  const fallbackSvg = `<svg viewBox="0 0 24 24" width="22" height="22" aria-label="${displayName}">
    <rect width="24" height="24" rx="6" fill="${palette.bg}"/>
    <text x="50%" y="54%" dominant-baseline="middle" text-anchor="middle" font-family="-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif" font-weight="700" font-size="12" fill="${palette.color}">${firstLetter}</text>
  </svg>`;

  return {
    id: "generic",
    name: displayName,
    color: palette.color,
    bgColor: palette.bg,
    borderColor: palette.border,
    svg: fallbackSvg,
    isFallback: true,
  };
}

